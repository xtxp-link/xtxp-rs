//! Seeded vector generator: random multi-round edits by 2 to 4 peers, every
//! operation valid against the generating peer's replica at that moment.

use rand::rngs::StdRng;
use rand::seq::SliceRandom;
use rand::{Rng, SeedableRng};
use std::collections::BTreeMap;
use xmesh::names::is_reserved;
use xmesh::vector::{Expect, Vector};
use xmesh::{Node, Op, Xmesh};

const SEED: &str = concat!(
    "<!-- fuzz -->",
    r#"<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape">"#,
    r#"<rect id="r1" x="1"/><g id="g1" inkscape:label="L"><circle id="c1"/>"#,
    "<text>hé<tspan>x</tspan> y</text></g><!--note--><ellipse id=\"e1\"/></svg>",
);
const FRAGMENTS: [&str; 5] = [
    "<rect/>",
    r#"<circle r="2"/>"#,
    "<g><rect/></g>",
    "t",
    "<!--c-->",
];
const ATTR_NAMES: [&str; 3] = ["fill", "x", "inkscape:label"];
const ATTR_VALUES: [&str; 4] = ["red", "1", "é😀", "a\"b<"];
const TEXTS: [&str; 3] = ["z", "ü", "😀"];

/// The vector for `seed`: the same seed always gives the same vector.
pub fn generate(seed: u64) -> Vector {
    let mut rng = StdRng::seed_from_u64(seed);
    let peer_count = rng.gen_range(2..=4u64);
    let peers: BTreeMap<String, u64> = (1..=peer_count).map(|i| (format!("p{i}"), i)).collect();
    let seed_update = Xmesh::seed(SEED).expect("fuzz seed is valid");
    let replicas: BTreeMap<String, Xmesh> = peers
        .iter()
        .map(|(name, &id)| {
            let replica = Xmesh::new(id).expect("small client IDs");
            replica.apply(&seed_update).expect("seed applies");
            (name.clone(), replica)
        })
        .collect();

    let mut rounds = Vec::new();
    for _ in 0..rng.gen_range(1..=5) {
        let mut round = BTreeMap::new();
        for (name, replica) in &replicas {
            let batches: Vec<Vec<Op>> = (0..rng.gen_range(1..=3))
                .map(|_| {
                    (0..rng.gen_range(1..=4))
                        .map(|_| {
                            let op = random_op(&mut rng, &replica.tree());
                            replica
                                .edit(std::slice::from_ref(&op))
                                .expect("generated ops are valid");
                            op
                        })
                        .collect()
                })
                .collect();
            round.insert(name.clone(), batches);
        }
        for a in replicas.values() {
            for b in replicas.values() {
                b.apply(&a.diff(&b.state_vector()).unwrap()).unwrap();
            }
        }
        rounds.push(round);
    }

    Vector {
        name: format!("fuzz-{seed}"),
        description: format!("Generated by xtxp-fuzzer from seed {seed}."),
        seed: SEED.to_string(),
        peers,
        rounds,
        expect: Expect::default(),
    }
}

/// Places in the document an op can target, as paths from the root element.
#[derive(Default)]
struct Targets {
    /// Elements that may take children and attributes (not reserved ones), root included.
    elements: Vec<(Vec<u32>, usize, Vec<String>)>,
    /// Text nodes with their text.
    texts: Vec<(Vec<u32>, String)>,
    /// Every node except the root element.
    nodes: Vec<Vec<u32>>,
}

fn collect(node: &Node, path: Vec<u32>, t: &mut Targets) {
    if !path.is_empty() {
        t.nodes.push(path.clone());
    }
    match node {
        Node::Text(text) => t.texts.push((path, text.clone())),
        Node::Element(e) => {
            if !is_reserved(&e.name) {
                let names = e.attrs.iter().map(|(k, _)| k.clone()).collect();
                t.elements.push((path.clone(), e.children.len(), names));
            }
            for (i, child) in e.children.iter().enumerate() {
                let mut p = path.clone();
                p.push(i as u32);
                collect(child, p, t);
            }
        }
    }
}

/// UTF-16 offsets that fall between characters.
fn boundaries(text: &str) -> Vec<u32> {
    let mut out = vec![0];
    let mut at = 0;
    for c in text.chars() {
        at += c.len_utf16() as u32;
        out.push(at);
    }
    out
}

fn pick<'a, T>(rng: &mut StdRng, items: &'a [T]) -> &'a T {
    items.choose(rng).expect("non-empty")
}

fn random_op(rng: &mut StdRng, tree: &[Node]) -> Op {
    let root = tree
        .iter()
        .find(|n| matches!(n, Node::Element(e) if !is_reserved(&e.name)))
        .expect("document has a root");
    let mut t = Targets::default();
    collect(root, vec![], &mut t);

    for _ in 0..16 {
        match rng.gen_range(0..7) {
            0 => {
                let (parent, len, _) = pick(rng, &t.elements).clone();
                let index = rng.gen_range(0..=len as u32);
                return Op::Insert {
                    parent,
                    index,
                    xml: pick(rng, &FRAGMENTS).to_string(),
                };
            }
            1 if !t.nodes.is_empty() => {
                return Op::Remove {
                    path: pick(rng, &t.nodes).clone(),
                };
            }
            2 => {
                let (path, _, _) = pick(rng, &t.elements).clone();
                return Op::SetAttr {
                    path,
                    name: pick(rng, &ATTR_NAMES).to_string(),
                    value: pick(rng, &ATTR_VALUES).to_string(),
                };
            }
            3 => {
                let with_attrs: Vec<_> = t
                    .elements
                    .iter()
                    .filter(|(_, _, a)| !a.is_empty())
                    .collect();
                if let Some((path, _, names)) = with_attrs.choose(rng) {
                    return Op::RemoveAttr {
                        path: path.clone(),
                        name: pick(rng, names).clone(),
                    };
                }
            }
            4 if !t.texts.is_empty() => {
                let (path, text) = pick(rng, &t.texts).clone();
                let offset = *pick(rng, &boundaries(&text));
                return Op::InsertText {
                    path,
                    offset,
                    text: pick(rng, &TEXTS).to_string(),
                };
            }
            5 => {
                let non_empty: Vec<_> = t.texts.iter().filter(|(_, s)| !s.is_empty()).collect();
                if let Some((path, text)) = non_empty.choose(rng) {
                    let b = boundaries(text);
                    let start = rng.gen_range(0..b.len() - 1);
                    let end = rng.gen_range(start + 1..b.len());
                    return Op::DeleteText {
                        path: path.clone(),
                        offset: b[start],
                        len: b[end] - b[start],
                    };
                }
            }
            6 if !t.nodes.is_empty() => {
                let path = pick(rng, &t.nodes).clone();
                let dests: Vec<_> = t
                    .elements
                    .iter()
                    .filter(|(p, _, _)| !p.starts_with(&path))
                    .collect();
                if let Some((new_parent, len, _)) = dests.choose(rng) {
                    let index = rng.gen_range(0..=*len as u32);
                    return Op::Move {
                        path,
                        new_parent: new_parent.clone(),
                        index,
                    };
                }
            }
            _ => {}
        }
    }
    Op::Insert {
        parent: vec![],
        index: 0,
        xml: "<rect/>".to_string(),
    }
}
